export function localizedPropertyName(definition: PropertyDefinition, locale: Locale) {
  const builtIn = builtInPropertyNames[definition.key];
  return builtIn && definition.name === builtIn.en ? (locale === "zh-CN" ? builtIn.zh : builtIn.en) : definition.name;
}

export function localizedOptionLabel(option: PropertyOption, locale: Locale) {
  const builtIn = builtInOptions[option.id];
  return builtIn && option.label === builtIn.en ? (locale === "zh-CN" ? builtIn.zh : builtIn.en) : option.label;
}
