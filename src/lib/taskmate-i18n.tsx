const dictionaries = { en, "zh-CN": zh };
const STORAGE_KEY = "taskmate.locale.v1";
type Translate = (key: TranslationKey, values?: Record<string, string | number>) => string;

const I18nContext = createContext<{ locale: Locale; setLocale(locale: Locale): void; t: Translate }>({
  locale: "en",
  setLocale: () => undefined,
  t: (key, values) => interpolate(en[key], values),
});

export function TaskmateI18nProvider({ children }: { children: ReactNode }) {
  const [locale, setLocale] = useState<Locale>(() => {
    const stored = localStorage.getItem(STORAGE_KEY);
    if (stored === "en" || stored === "zh-CN") return stored;
    return navigator.language.toLowerCase().startsWith("zh") ? "zh-CN" : "en";
  });
  useEffect(() => {
    localStorage.setItem(STORAGE_KEY, locale);
    document.documentElement.lang = locale;
  }, [locale]);
  const value = useMemo(() => ({
    locale,
    setLocale,
    t: ((key, values) => {
      return interpolate(dictionaries[locale][key] ?? en[key], values);
    }) as Translate,
  }), [locale]);
  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useTaskmateI18n() {
  return useContext(I18nContext);
}

function interpolate(message: string, values?: Record<string, string | number>) {
  for (const [name, replacement] of Object.entries(values ?? {})) {
    message = message.replaceAll(`{${name}}`, String(replacement));
  }
  return message;
}

